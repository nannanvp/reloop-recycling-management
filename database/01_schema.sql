SET DEFINE OFF
CREATE TABLE rc_centres (
 id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 name VARCHAR2(120) NOT NULL UNIQUE, address VARCHAR2(500) NOT NULL,
 active NUMBER(1) DEFAULT 1 NOT NULL CHECK (active IN (0,1))
);
CREATE TABLE rc_users (
 id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 full_name VARCHAR2(120) NOT NULL, email VARCHAR2(200) NOT NULL UNIQUE,
 password_hash VARCHAR2(100) NOT NULL,
 role VARCHAR2(10) NOT NULL CHECK (role IN ('ADMIN','STAFF','CITIZEN')),
 centre_id NUMBER REFERENCES rc_centres(id),
 active NUMBER(1) DEFAULT 1 NOT NULL CHECK (active IN (0,1)),
 CONSTRAINT ck_staff_centre CHECK (role <> 'STAFF' OR centre_id IS NOT NULL),
 CONSTRAINT ck_email_normalized CHECK (email=LOWER(TRIM(email)))
);
CREATE TABLE rc_materials (
 id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 name VARCHAR2(100) NOT NULL UNIQUE,
 points_per_kg NUMBER(8) DEFAULT 10 NOT NULL CHECK(points_per_kg>=0),
 active NUMBER(1) DEFAULT 1 NOT NULL CHECK(active IN(0,1))
);
CREATE TABLE rc_pickups (
 id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 citizen_id NUMBER NOT NULL REFERENCES rc_users(id),
 centre_id NUMBER NOT NULL REFERENCES rc_centres(id),
 pickup_address VARCHAR2(500) NOT NULL, preferred_date DATE NOT NULL,
 scheduled_date DATE,
 status VARCHAR2(12) DEFAULT 'REQUESTED' NOT NULL CHECK(status IN('REQUESTED','SCHEDULED','COLLECTED','CANCELLED')),
 notes VARCHAR2(1000), created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE rc_batches (
 id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 centre_id NUMBER NOT NULL REFERENCES rc_centres(id),
 material_id NUMBER NOT NULL REFERENCES rc_materials(id),
 output_kg NUMBER(10,3) NOT NULL CHECK(output_kg>=0),
 processed_by NUMBER NOT NULL REFERENCES rc_users(id),
 processed_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE rc_pickup_items (
 id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 pickup_id NUMBER NOT NULL REFERENCES rc_pickups(id) ON DELETE CASCADE,
 material_id NUMBER NOT NULL REFERENCES rc_materials(id),
 estimated_kg NUMBER(10,3) NOT NULL CHECK(estimated_kg>0),
 collected_kg NUMBER(10,3), accepted_kg NUMBER(10,3),
 batch_id NUMBER REFERENCES rc_batches(id),
 CONSTRAINT uq_pickup_material UNIQUE(pickup_id,material_id),
 CONSTRAINT ck_collected_weight CHECK(collected_kg IS NULL OR collected_kg>=0),
 CONSTRAINT ck_accepted_weight CHECK(accepted_kg IS NULL OR (collected_kg IS NOT NULL AND accepted_kg>=0 AND accepted_kg<=collected_kg))
);
CREATE TABLE rc_reward_ledger (
 id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 pickup_item_id NUMBER NOT NULL UNIQUE REFERENCES rc_pickup_items(id),
 rate_snapshot NUMBER(8) NOT NULL CHECK(rate_snapshot>=0),
 points NUMBER(12) NOT NULL CHECK(points>=0),
 posted_by NUMBER NOT NULL REFERENCES rc_users(id),
 created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE rc_audit_log (
 id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 pickup_id NUMBER NOT NULL REFERENCES rc_pickups(id) ON DELETE CASCADE,
 old_status VARCHAR2(12), new_status VARCHAR2(12),
 database_user VARCHAR2(128), actor_identifier VARCHAR2(128),
 created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_users_centre ON rc_users(centre_id);
CREATE INDEX ix_pickups_citizen ON rc_pickups(citizen_id);
CREATE INDEX ix_pickups_centre_status ON rc_pickups(centre_id,status,preferred_date);
CREATE INDEX ix_items_material ON rc_pickup_items(material_id);
CREATE INDEX ix_items_batch ON rc_pickup_items(batch_id);
CREATE INDEX ix_batches_centre ON rc_batches(centre_id,material_id);
CREATE INDEX ix_batches_material ON rc_batches(material_id);
CREATE INDEX ix_batches_actor ON rc_batches(processed_by);
CREATE INDEX ix_rewards_actor ON rc_reward_ledger(posted_by);
CREATE INDEX ix_audit_pickup ON rc_audit_log(pickup_id);
COMMENT ON TABLE rc_pickups IS 'Pickup header; address is a historical snapshot';
COMMENT ON TABLE rc_reward_ledger IS 'Immutable illustrative points; historical rate snapshot';
